"""Report source modules that are neither shipped nor deliberately retired.

tools/build.py assembles MODULES and refuses to ship anything that reads an
UNWIRED_MODULES entry. But a module in NEITHER list is invisible to that safety
net: it sits in the tree, tests may load it, and nothing tells the reader whether
it is live. This lists those orphans so each one is either wired or retired on
purpose.

Usage:  python tools/orphan_audit.py
Writes: docs/ORPHAN_AUDIT.md
"""
import io
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def main():
    src = io.open(os.path.join(ROOT, "tools", "build.py"), encoding="utf-8").read()
    # The shipped list must be read from the region BEFORE UNWIRED_MODULES.
    # Matching the whole file made every retired entry look shipped too, which
    # reported 18 shipped modules when the build assembles 9. Found by the
    # verification reviewer; the numbers it invalidated are corrected below.
    mods_region = src[:src.find("UNWIRED_MODULES")]
    shipped = [m for m, _ in re.findall(r'\("(src/[^"]+)",\s*"([^"]+)"\)', mods_region)]
    block = src[src.find("UNWIRED_MODULES"):src.find("BANNED_IN_OUTPUT")]
    retired = [m for m, _ in re.findall(r'\("(src/[^"]+)",\s*"([^"]+)"\)', block)]
    # U28: modules loaded by tools/ and by their own tests but never assembled.
    # Reported on their own so they do not read as orphans.
    ablock = src[src.find("AUDIT_ONLY_MODULES"):src.find("PUBLISHED_BY")]
    audit_only = [m for m, _ in re.findall(r'\("(src/[^"]+)",\s*"([^"]+)"\)', ablock)]

    on_disk = []
    for base, _d, files in os.walk(os.path.join(ROOT, "src")):
        for f in files:
            if f.endswith(".js"):
                rel = os.path.relpath(os.path.join(base, f), ROOT).replace("\\", "/")
                on_disk.append(rel)
    on_disk.sort()

    orphans = [m for m in on_disk
               if m not in shipped and m not in retired and m not in audit_only]

    # Which tests load each orphan?
    loaders = {}
    for base, _d, files in os.walk(os.path.join(ROOT, "tests")):
        if "_out" in base or "_profile" in base or "fixtures" in base:
            continue
        for f in files:
            if not f.endswith((".mjs", ".cjs", ".js", ".py")):
                continue
            p = os.path.join(base, f)
            try:
                text = io.open(p, encoding="utf-8", errors="ignore").read()
            except OSError:
                continue
            for m in orphans:
                stem = os.path.basename(m)
                folder = m.split("/")[1]
                if stem in text and folder in text:
                    # A bare substring match is not a load. A test that NAMES a
                    # module in order to assert it is NOT loaded is not loading
                    # it, and reporting that as a misdirected load is a false
                    # positive. Require an import/require/read-the-file shape.
                    loaded = False
                    for pat in (r'(?:require|import)\s*\(?[^\n]*' + re.escape(stem),
                                r"['\"]\.\.?/[^'\"]*" + re.escape(stem),
                                r'loadSource[^\n]*' + re.escape(stem),
                                r'readFileSync[^\n]*' + re.escape(stem)):
                        if re.search(pat, text):
                            loaded = True
                            break
                    if loaded:
                        loaders.setdefault(m, []).append(
                            os.path.relpath(p, ROOT).replace("\\", "/"))

    lines = ["# Modules that are neither shipped nor retired", "",
             "Generated by `tools/orphan_audit.py`.",
             "The build's guard only covers modules it knows about. These are in neither",
             "list, so nothing states whether they are live.", "",
             "## Shipped", ""]
    for m in shipped:
        lines.append("- `%s`" % m)
    lines += ["", "## Deliberately retired", ""]
    for m in retired:
        lines.append("- `%s`" % m)
    lines += ["", "## Loaded by tools/ and tests, never assembled (audit-only)", ""]
    for m in audit_only:
        lines.append("- `%s`" % m)
    lines += ["", "## ORPHANS (in neither list)", ""]
    if not orphans:
        lines.append("None.")
    for m in orphans:
        lines.append("- `%s`%s" % (m, (" - loaded by: " + ", ".join(sorted(loaders[m])))
                                   if m in loaders else " - loaded by no test"))
    lines += ["", "## Summary", "",
              "%d .js modules on disk, %d shipped, %d deliberately retired, "
              "%d audit-only, %d orphaned."
              % (len(on_disk), len(shipped), len(retired), len(audit_only), len(orphans)), ""]

    out = os.path.join(ROOT, "docs", "ORPHAN_AUDIT.md")
    io.open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")

    print("shipped :", len(shipped))
    print("retired :", len(retired))
    print("audit-only :", len(audit_only))
    print("ORPHANS :", len(orphans))
    for m in orphans:
        print("   %s" % m)
        for t in sorted(loaders.get(m, [])) or ["(no test loads it)"]:
            print("        loaded by %s" % t)
    print("wrote", out)


if __name__ == "__main__":
    main()
