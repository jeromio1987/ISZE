def bar_rows(items: list[dict]) -> str:
    mx = max(i["eur"] for i in items) or 1
    rows = []
    for i in items:
        pct = 100.0 * i["eur"] / mx
        rows.append(
            f'<div class="bar-row"><div class="bn">{i["name"]}</div>'
            f'<div class="bb"><div class="bf" style="width:{pct:.1f}%"></div></div>'
            f'<div class="bv">€{i["eur"]:,.0f}</div>'
            f'<div class="bno">{i["note"]}</div></div>'
        )
    return "\n".join(rows)


def kpi_html(kpis: list[dict]) -> str:
    bits = []
    for k in kpis:
        cls = f' kpi {k.get("cls","")}'.rstrip()
        bits.append(
            f'<div class="{cls.strip()}"><div class="lab">{k["lab"]} '
            f'<span class="info" tabindex="0">i<span class="tip">{k["tip"]}</span></span></div>'
            f'<div class="val">{k["val"]}</div><div class="note">{k["note"]}</div></div>'
        )
    return "\n".join(bits)


def li(items: list[str]) -> str:
    return "\n".join(f"<li>{x}</li>" for x in items)


def mile_html(ms: list[dict]) -> str:
    return "\n".join(
        f'<div class="mile"><div class="mw">{m["when"]}</div><div class="mt">{m["what"]}</div></div>'
        for m in ms
    )


def ladder_rows(items: list[dict]) -> str:
    return "\n".join(
        f'<tr><td><b>{r["rung"]}</b></td><td>{r["what"]}</td>'
        f'<td>{r["label"]}</td><td>{r["when"]}</td></tr>'
        for r in items
    )


